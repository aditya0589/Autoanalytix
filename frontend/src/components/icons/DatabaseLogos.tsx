/**
 * Convenience Helper for dynamically rendering logos by source type
 */
export const DatabaseSourceLogo: React.FC<{ type: string; className?: string; size?: number }> = ({
  type,
  className = "w-5 h-5",
  size,
}) => {
  const t = (type || "").toLowerCase();
  if (t === "postgresql" || t === "postgres" || t === "psql") {
    return <PostgresLogo className={className} size={size} />;
  }
  if (t === "bigquery" || t === "google_bigquery") {
    return <BigQueryLogo className={className} size={size} />;
  }
  if (t === "snowflake") {
    return <SnowflakeLogo className={className} size={size} />;
  }
  if (t === "databricks" || t === "delta_lake") {
    return <DatabricksLogo className={className} size={size} />;
  }
  if (t === "sqlite" || t === "sqlite3") {
    return <SQLiteLogo className={className} size={size} />;
  }
  if (t === "google_sheet" || t === "gsheet" || t === "sheets" || t === "sheet") {
    return <GoogleSheetsLogo className={className} size={size} />;
  }
  return null;
};
